/* ═══ Language Meta ═══ */
const LANG_META = {
  ar: { flag: "🇩🇿", code: "AR", dir: "rtl", label: "العربية" },
  en: { flag: "🇬🇧", code: "EN", dir: "ltr", label: "English" },
  fr: { flag: "🇫🇷", code: "FR", dir: "ltr", label: "Français" },
  ru: { flag: "🇷🇺", code: "RU", dir: "ltr", label: "Русский" }
};

/* ═══ Apply Language ═══ */
function applyLanguage(lang) {
  if (!I18N[lang]) lang = "ar";
  
  const meta = LANG_META[lang];
  const html = document.documentElement;
  const body = document.body;
  
  html.lang = lang;
  html.dir = meta.dir;
  body.dir = meta.dir;
  
  // Update all i18n elements
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (I18N[lang][key]) {
      el.textContent = I18N[lang][key];
    }
  });
  
  // Update title
  const titleEl = document.querySelector("title");
  if (titleEl) titleEl.textContent = I18N[lang]["meta.title"];
  
  // Update lang button
  const langBtn = document.getElementById("langBtn");
  if (langBtn) {
    langBtn.querySelector(".flag").textContent = meta.flag;
    langBtn.querySelector(".code").textContent = meta.code;
  }
  
  // Save preference
  localStorage.setItem("ummah_lang", lang);
  
  // Update URL
  const url = new URL(window.location);
  url.searchParams.set("lang", lang);
  window.history.replaceState({}, "", url);
}

